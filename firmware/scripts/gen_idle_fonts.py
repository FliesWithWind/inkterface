#!/usr/bin/env python3
"""Generate firmware/src/ee05/idle_fonts_data.cpp: 1-bit Inkterface Mono bitmaps for the idle
renderer (font ids/sizes/charsets are part of the layout wire format, see docs/idle-mode.md).

    python3 firmware/scripts/gen_idle_fonts.py          # rewrites the .cpp
    python3 firmware/scripts/gen_idle_fonts.py --check  # exit 1 if the committed file is stale

Needs Pillow with FreeType (the vendored one: PYTHONPATH=decky/py_modules, FreeType 2.14.3; the bitmaps depend on the FreeType version).
Inkterface Mono is IBM Plex Mono without its hinting instructions (decky/scripts/make_inkterface_mono.py), so FreeType hints it with its
auto-hinter: every glyph of a size gets the same stem width. Glyphs are then thresholded 1-bit, tight bounding box, rows byte-aligned
MSB first (1 = ink). OFL-1.1 (decky/py_modules/inkterface_core/screens/fonts/OFL.txt).
"""
import os
import sys

from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
OUT = os.path.join(ROOT, "firmware", "src", "ee05", "idle_fonts_data.cpp")
# the plugin-bundled copies: the same files the Decky renderer draws with
_FONTS = os.path.join(ROOT, "decky", "py_modules", "inkterface_core", "screens", "fonts")
TTF = {
    "regular": os.path.join(_FONTS, "InkterfaceMono-Regular.ttf"),
    "bold": os.path.join(_FONTS, "InkterfaceMono-Bold.ttf"),
}
FULL = list(range(32, 127)) + [0x7F]
DIGITS = sorted(ord(c) for c in "0123456789:.-/% ") + [0x7F]  # codes must be sorted (binary search)
# (id, style, px, charset)
FONTS = (
    [(i, "regular", px, FULL) for i, px in enumerate((14, 18, 22, 28, 36, 48))]
    + [(8 + i, "bold", px, FULL) for i, px in enumerate((14, 18, 22, 28, 36, 48))]
    + [(16 + i, "bold", px, DIGITS) for i, px in enumerate((80, 120, 160))]
)


def load_font(style, px):
    return ImageFont.truetype(TTF[style], px, layout_engine=ImageFont.Layout.BASIC)


def glyph(font, px, code):
    ch = "\u00b0" if code == 0x7F else chr(code)
    adv = round(font.getlength("0"))  # monospaced
    if ch == " ":
        return b"", 0, 0, adv, 0, 0
    pad = px
    im = Image.new("L", (px * 2 + 2 * pad, px * 3), 0)
    d = ImageDraw.Draw(im)
    d.fontmode = "1"
    base = px * 2
    d.text((pad, base), ch, font=font, fill=255, anchor="ls")
    im = im.point(lambda v: 255 if v >= 128 else 0)
    box = im.getbbox()
    if box is None:
        return b"", 0, 0, adv, 0, 0
    x0, y0, x1, y1 = box
    w, h = x1 - x0, y1 - y0
    stride = (w + 7) // 8
    data = bytearray(stride * h)
    px_ = im.load()
    for y in range(h):
        for x in range(w):
            if px_[x0 + x, y0 + y]:
                data[y * stride + x // 8] |= 0x80 >> (x % 8)
    return bytes(data), w, h, adv, x0 - pad, y0 - base


def build():
    out = [
        "// GENERATED by firmware/scripts/gen_idle_fonts.py from Inkterface Mono = IBM Plex Mono without hinting instructions (SIL OFL 1.1). Do not edit.",
        '#include "idle_fonts.h"',
        "",
        "namespace idle {",
        "namespace {",
    ]
    names = {}
    for fid, style, px, chars in FONTS:
        font = load_font(style, px)
        asc, desc = font.getmetrics()
        bm, glyphs = bytearray(), []
        for code in chars:
            data, w, h, adv, xo, yo = glyph(font, px, code)
            glyphs.append((len(bm), w, h, adv, xo, yo))
            bm += data
        n = f"f{fid}"
        names[fid] = n
        out.append(f"// id {fid}: {style} {px}px, {len(chars)} glyphs, {len(bm)} bitmap bytes")
        out.append(f"const uint8_t {n}_bm[] = {{")
        for i in range(0, len(bm), 24):
            out.append("    " + ",".join(f"0x{b:02X}" for b in bm[i : i + 24]) + ",")
        if not bm:
            out.append("    0,")
        out.append("};")
        out.append(f"const Glyph {n}_g[] = {{")
        for off, w, h, adv, xo, yo in glyphs:
            out.append(f"    {{{off}u,{w},{h},{adv},{xo},{yo}}},")
        out.append("};")
        out.append(f"const uint8_t {n}_c[] = {{" + ",".join(str(c) for c in chars) + "};")
        out.append(f"const Font {n} = {{{n}_bm, {n}_g, {n}_c, {len(chars)}, {px}, {asc}, {asc + desc}}};")
        out.append("")
    out.append("}  // namespace")
    out.append("")
    out.append("const Font *const kFontById[FONT_SLOTS] = {")
    for i in range(19):
        out.append(f"    {'&' + names[i] if i in names else 'nullptr'},")
    out.append("};")
    out.append("")
    out.append("}  // namespace idle")
    return "\n".join(out) + "\n"


def main():
    text = build()
    if "--check" in sys.argv:
        cur = open(OUT).read() if os.path.exists(OUT) else ""
        sys.exit(0 if cur == text else 1)
    open(OUT, "w").write(text)
    print(f"wrote {OUT} ({len(text)} bytes of source)")


if __name__ == "__main__":
    main()
