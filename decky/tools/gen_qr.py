"""Prints src/components/qrData.ts: the QR code of the Steam Web API key page, as rows of '#' and '.'.
It is a constant because the plugin has no QR library (and needs none for one fixed link). Run it only if the URL changes:
    uv run --python 3.14 --no-project --with segno python decky/tools/gen_qr.py > decky/src/components/qrData.ts
Check the result by decoding a rendered copy, e.g. with OpenCV:
    cv2.QRCodeDetector().detectAndDecode(image)   # must return the URL
"""
import segno

URL = "https://steamcommunity.com/dev/apikey"
q = segno.make(URL, error="m", micro=False, boost_error=False)   # version 3, error correction M, 29 x 29 modules
rows = ["".join("#" if c else "." for c in r) for r in q.matrix]
print("// Generated by decky/tools/gen_qr.py. Do not edit by hand: the test decodes its structure and checks the URL.")
print(f'export const API_KEY_URL = "{URL}";')
print("/** Modules of the QR code for API_KEY_URL ('#' dark, '.' light), without the quiet zone. */")
print("export const API_KEY_QR = [")
for r in rows:
    print(f'  "{r}",')
print("] as const;")
