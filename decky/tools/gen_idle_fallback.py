#!/usr/bin/env python3
"""Regenerate firmware/src/ee05/idle_fallback.h: the built-in layout the panel shows when no valid
store is in flash (minimal-clock, compiled by the real host compiler).
  python3 decky/tools/gen_idle_fallback.py          # rewrite
  python3 decky/tools/gen_idle_fallback.py --check  # exit 1 if stale"""
import json
import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
sys.path.insert(0, os.path.join(ROOT, "decky", "py_modules"))
from inkterface_core.idle.compile import compile_layout  # noqa: E402

OUT = os.path.join(ROOT, "firmware", "src", "ee05", "idle_fallback.h")


def build() -> str:
    scr = json.load(open(os.path.join(ROOT, "decky", "screens", "minimal-clock", "screen.json"), encoding="utf-8"))
    blob = compile_layout(scr["idle"])
    rows = [", ".join(f"0x{b:02X}" for b in blob[i:i + 16]) for i in range(0, len(blob), 16)]
    return ("// GENERATED by decky/tools/gen_idle_fallback.py from decky/screens/minimal-clock. Do not edit.\n"
            "#pragma once\n#include <stddef.h>\n#include <stdint.h>\n\n"
            "namespace idle {\nstatic const uint8_t kFallbackLayout[] = {\n    " + ",\n    ".join(rows) + ",\n};\n"
            "static const size_t kFallbackLayoutLen = sizeof(kFallbackLayout);\n}  // namespace idle\n")


if __name__ == "__main__":
    text = build()
    if "--check" in sys.argv:
        sys.exit(0 if os.path.exists(OUT) and open(OUT).read() == text else 1)
    open(OUT, "w").write(text)
    print("wrote", OUT)
